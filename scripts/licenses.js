// Generates THIRD_PARTY_LICENSES.md from the packages esbuild actually bundles
// into dist/extension.js (read from its metafile), so the notices shipped in
// the .vsix always match the code shipped in it.
//
//   node scripts/licenses.js           regenerate THIRD_PARTY_LICENSES.md
//   node scripts/licenses.js --check   fail if it is out of date (for CI)
//
// Fails if any bundled package's license is outside ALLOWED.
const esbuild = require('esbuild');
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const OUTPUT = path.join(ROOT, 'THIRD_PARTY_LICENSES.md');
const ALLOWED = new Set(['MIT', 'ISC', 'Apache-2.0', 'BSD-2-Clause', 'BSD-3-Clause', '0BSD']);

async function bundledPackageDirs() {
  // Same entry and externals as esbuild.js; only the input list matters here.
  const result = await esbuild.build({
    absWorkingDir: ROOT,
    entryPoints: ['src/extension.ts'],
    bundle: true,
    external: ['vscode'],
    format: 'cjs',
    platform: 'node',
    target: 'node18',
    write: false,
    metafile: true,
    logLevel: 'silent',
  });
  const dirs = new Set();
  for (const input of Object.keys(result.metafile.inputs)) {
    // The innermost node_modules segment names the package (handles nesting and scopes).
    const match = /^(.*node_modules\/(?:@[^/]+\/)?[^/]+)\//.exec(input);
    if (match) dirs.add(path.join(ROOT, match[1]));
  }
  return [...dirs];
}

function readFirst(dir, pattern) {
  const name = fs.readdirSync(dir).find((f) => pattern.test(f));
  return name ? fs.readFileSync(path.join(dir, name), 'utf8').trim() : undefined;
}

function describe(dir) {
  const pkg = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
  const license = typeof pkg.license === 'string' ? pkg.license : pkg.license?.type;
  const repo = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url;
  return {
    name: pkg.name,
    version: pkg.version,
    license: license ?? 'UNKNOWN',
    repository: repo?.replace(/^git\+/, '').replace(/^git:\/\//, 'https://').replace(/\.git$/, ''),
    licenseText: readFirst(dir, /^(LICEN[CS]E|COPYING)(\.(md|txt))?$/i),
    noticeText: readFirst(dir, /^NOTICE(\.(md|txt))?$/i),
  };
}

function render(packages) {
  const lines = [
    '# Third-party licenses',
    '',
    '<!-- Generated by scripts/licenses.js from the packages bundled into dist/extension.js. Do not edit by hand; run `npm run licenses`. -->',
    '',
    "Snagboat's own code is MIT licensed (see [LICENSE](LICENSE)). The packaged extension bundles the following third-party packages, whose license notices are reproduced below as their licenses require. Development-only tools (TypeScript, esbuild, mocha, `@vscode/test-electron`, `@vscode/vsce`) are not shipped.",
    '',
    '| Package | Version | License |',
    '| --- | --- | --- |',
    ...packages.map((p) => `| ${p.repository ? `[${p.name}](${p.repository})` : p.name} | ${p.version} | ${p.license} |`),
  ];
  for (const p of packages) {
    lines.push('', `## ${p.name} ${p.version}`, '', `License: ${p.license}`, '');
    lines.push('```text', p.licenseText ?? `No license file found in the package; its package.json declares ${p.license}.`, '```');
    if (p.noticeText) lines.push('', 'NOTICE:', '', '```text', p.noticeText, '```');
  }
  return lines.join('\n') + '\n';
}

async function main() {
  const packages = (await bundledPackageDirs()).map(describe).sort((a, b) => a.name.localeCompare(b.name));
  const disallowed = packages.filter((p) => !ALLOWED.has(p.license));
  if (disallowed.length > 0) {
    console.error(`Bundled packages with licenses outside the allowlist: ${disallowed.map((p) => `${p.name} (${p.license})`).join(', ')}`);
    process.exit(1);
  }

  const output = render(packages);
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, 'utf8') : '';
    if (current !== output) {
      console.error('THIRD_PARTY_LICENSES.md is out of date with the bundled dependencies. Run `npm run licenses` and commit the result.');
      process.exit(1);
    }
    console.log(`THIRD_PARTY_LICENSES.md is up to date (${packages.length} bundled packages).`);
    return;
  }
  fs.writeFileSync(OUTPUT, output);
  console.log(`Wrote THIRD_PARTY_LICENSES.md for ${packages.length} bundled packages: ${packages.map((p) => `${p.name}@${p.version} (${p.license})`).join(', ')}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
